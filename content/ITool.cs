// A reference/calculator lesson: explanation + key takeaway + an interactive widget,
// deliberately NOT an IConcept. There's no code editor, no test cases, and no
// completion tracking -- "did you use the subnet calculator" isn't a pass/fail thing
// the way "did SumArray return the right value" is. If a tool's topic later grows real
// practice problems (e.g. "write a function that validates an IP string"), that
// becomes a separate IConcept in the same Section, not a retrofit of this interface.
public interface ITool
{
    string Id { get; }
    string Section { get; }
    string Track { get; }

    // See IConcept.Order -- same purpose, same default.
    int Order => 100;

    string Title { get; }
    string OneLiner { get; }
    string KeyTakeaway { get; }
    string Explanation { get; }
    ToolKind ToolKind { get; }
}

public record ToolDetail(
    string Id,
    string Section,
    string Track,
    string Title,
    string OneLiner,
    string KeyTakeaway,
    string Explanation,
    ToolKind ToolKind
);
